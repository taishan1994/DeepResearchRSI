SEC_26 = """### 2.6 读错单位会让「文件被截断」成为幻觉

字节数与字符数在非 ASCII 文本上差 2–3 倍。把字节当字符，
会得出「文件被截断了」的错误结论，然后去修一个不存在的问题。

**怎么发现的**：某次插入后用 `len(s)` 与 `stat().st_size` 对比，
看到 13,363 → 8,634，据此判断「内容被我的切片截断」，
差点回滚重写。实际是前者为字节、后者为字符（中文占 3 字节），
文件完好无损。同一个错误在本项目里出现过**两次**。

**怎么用**：报文件大小时永远带单位（`8,634 字符 / 16,588 字节`）。
判「是否被截断」不要看总长度，要看**结构标记**——
小节数、标题数、关键锚点是否存在。长度是间接指标，结构是直接指标。

"""


