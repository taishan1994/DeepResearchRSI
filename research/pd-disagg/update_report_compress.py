"""把「压缩」这一轮写进 REPORT 与 LESSONS。

## REPORT

补 1.9，说明压缩做了什么、没做什么。

## LESSONS

这一轮的教训是：**连载式写作会让判据散落**。
每加一层维度，都在文末追加一段「与前面几节的关系」，
三次之后读者要读到 18 页才知道判据全貌。

修法不是删内容，是**增加一个入口**并清掉过程叙述。
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
REPORT = ROOT / "research" / "pd-disagg" / "REPORT.md"
LESSONS = ROOT / "docs" / "LESSONS.md"

REPORT_SEC = """## 1.9 第 7 轮：压一次

六轮加下来，论文 18 页，但判据散在五处：sec6 的「判据汇总」、
sec8 的「怎么选三条判据」、sec9 的三平面、sec10 的「由此得到的判据」、
sec11 的「这一步在判据里的位置」。**读者要读到 18 页才知道判据全貌。**

压缩的形态不是删内容——细节都有价值。做的是三件事：

### 1）新增第 2 节「一页判据」

- 一张四步流程图（负载形态 → SLO 形状 → 查窗口 → 每类选一个）
- 一张六层关系表（每层回答什么、能否决什么、在哪一节）
- 四条「本文没有回答什么」

关键是表里那一列「能否决什么」：**前四层是否决层，后三层是执行层**。
常见错误是把六层当清单逐条做——那会做很多本不该做的事。

### 2）删掉正文里的写作过程叙述

清出 5 处：「第 1 轮写这篇时」「本轮找到了已做完这件事的工作」
「上一轮我把…列为待做」「第三条的措辞在本轮被改过」。
这些属于 REPORT，不属于论文。读者不关心作者第几轮知道了什么。

判据：**「本轮」有两种**。会话的轮（agentic turn）要保留，
写作的轮要删。sec9 与 sec11 里的「下一轮」指会话轮次，保留了。

### 3）合并重复的「与前面几节的关系」

sec9 / sec10 / sec11 各有一段，结构相同、内容层层叠加。
叠加本身对（每加一层要重新收拢），但读到第三次就是重复。
sec10 与 sec11 各压成一小段，保留「本层新增的判断力」，
把重新列举前三节的部分换成指向判据页的交叉引用。共减 772 字符。

### 净效果

页数仍是 18——新增一页判据，同时删掉重复与过程叙述。
**页数没变，但入口多了一个。** 这是压缩的正确形态：
不是变短，是让读者不必读完才能用。

### 一处自查

压缩时把「故它\\进有窗口」的错字写进了新文件（应为「只有」），
编译不报错——LaTeX 把它当普通字排出。是读源码时发现的。
这已是同类错误的第三次，说明**新写的 LaTeX 也必须过
check_tex_escapes.py**，不能只在改旧文件时用。

"""

LESSON = """### 1.11 连载式写作会让判据散落

一层一层往上加内容时，每加一层都顺手在文末补一段「这层与前面几层的关系」。
单看每一段都是对的、必要的。但加完六层回头一看，**判据散在五个地方**，
读者要读完 18 页才知道全貌,而且每段都在重新列举前几层。

**为什么危险**:这不是内容错误,是**组织失效**。所有检查都是绿的
——证据完整、数值可回溯、审计通过——因为它们检查的是「每句话对不对」,
不检查「读完要多久才能用」。这类问题的特征是:
**产物完全正确,但不可用。**

**怎么用**:加第三层以上时,必须回头做一次「收拢」:
把散落的判据收进一个单独的前置小节,给出一张流程图或表,
并保留原有的细节小节。**不是删,是加一个入口。**

**配套的两条**:

  · **删掉写作过程叙述**。正文里出现「本轮发现」「上一轮我列为待做」
    是连载式写作的残留,属于工作日志,不属于论文。
    判据:区分「会话的轮」与「写作的轮」——前者是领域概念,要保留。
  · **重复的关系段要合并**。第一次收拢是必要的,第三次就是重复。

**一个反直觉的检验**:压缩后页数可能**一点没少**。
若新增了入口、删掉了重复,页数不变是正常的;
如果只追求页数下降,就会删掉有价值的细节。**压缩的目标是可用性,不是厚度。**

"""


def main() -> int:
    r = REPORT.read_text(encoding="utf-8")
    if "第 7 轮：压一次" not in r:
        anchor = "## 2. 交付物"
        i = r.find(anchor)
        if i < 0:
            print("[!] REPORT 锚点未找到")
        else:
            r = r[:i] + REPORT_SEC + r[i:]
            REPORT.write_text(r, encoding="utf-8", newline="\n")
            print("REPORT 已补压缩一节")
    else:
        print("REPORT 已含压缩一节")

    s = LESSONS.read_text(encoding="utf-8")
    if "1.11 连载式写作" not in s:
        anchor = "## 二、数字与产物"
        i = s.find(anchor)
        if i < 0:
            print("[!] LESSONS 锚点未找到")
        else:
            sep = "---" + chr(10) + chr(10)
            j = s.rfind(sep, 0, i)
            pos = j if j > 0 else i
            s = s[:pos] + LESSON + s[pos:]
            LESSONS.write_text(s, encoding="utf-8", newline="\n")
            print("LESSONS 已补 1.11")
    else:
        print("LESSONS 已含 1.11")

    print(f"\nREPORT {len(r):,} 字符 | LESSONS {len(s):,} 字符")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
